#!/usr/bin/env node
// Builds the iOS app's private assets from YOUR licensed files into mobile/assets/private/
// (git-ignored: this repo is public, and neither Pangram's nor Craftwork's licence allows
// sharing the files):
//   fonts/neuemontreal-{regular,medium,bold}.otf   Neue Montreal (Pangram Pangram, App licence)
//   basil.json                                      Basil Icons path data (Craftwork)
//   bars/<role>-<outline|solid>@{1,2,3}x.png        Basil icons as images: native bars need images
//   index.ts                                        the manifest the app imports as @rack/private
// Without index.ts the app uses src/private/fallback.ts: SF Pro and SF Symbols.
//
// Usage (from mobile/): npm run private-assets [-- <fonts dir> <basil.generated.ts>]
// Defaults: the web app's ../frontend/public/fonts and ../frontend/src/components/icons/basil.generated.ts
// (made by `npm run icons` in frontend/). Either may be missing; the other is still built.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "..");
const out = join(app, "assets/private");
const fontsDir = resolve(process.argv[2] ?? join(app, "../frontend/public/fonts"));
const basilFile = resolve(process.argv[3] ?? join(app, "../frontend/src/components/icons/basil.generated.ts"));

/** Font family names the app uses (src/theme/type.ts). */
const FONT_FILES = {
  "NeueMontreal-Regular": "neuemontreal-regular.otf",
  "NeueMontreal-Medium": "neuemontreal-medium.otf",
  "NeueMontreal-Bold": "neuemontreal-bold.otf",
};
/** Tab bar roles drawn as images. Saved (bookmark, user's choice) and Wardrobe (no Basil icon) are
 *  SF Symbols. Header buttons use SF
 *  Symbols: an image button there got its own tinted background, apart from the other buttons. */
const BAR_ROLES = ["feed", "hunts"];
const BAR_POINTS = 24; // tab bar and navigation bar icons

/** Only <path> elements with plain path data, as written by frontend/scripts/basil-icons.mjs. */
function checkMarkup(markup) {
  const elements = markup.match(/<[a-zA-Z][^>]*>/g) ?? [];
  for (const el of elements) {
    if (!el.startsWith("<path")) throw new Error(`unexpected element ${el.slice(0, 30)}`);
  }
  return markup;
}

function readBasil(file) {
  const src = readFileSync(file, "utf8");
  const start = src.indexOf("= {");
  const end = src.lastIndexOf("};");
  if (start < 0 || end < 0) throw new Error(`${file}: not a basil.generated.ts file`);
  const pack = JSON.parse(src.slice(start + 2, end + 1));
  for (const [role, v] of Object.entries(pack)) {
    if (typeof v?.outline !== "string" || typeof v?.solid !== "string") throw new Error(`bad entry ${role}`);
    checkMarkup(v.outline);
    checkMarkup(v.solid);
  }
  return pack;
}

function png(markup, px) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${px}" height="${px}" color="#000">${markup}</svg>`;
  return new Resvg(svg, { fitTo: { mode: "width", value: px } }).render().asPng();
}

// start clean, but keep the tracked README.md
for (const p of ["fonts", "bars", "basil.json", "index.ts"]) rmSync(join(out, p), { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const lines = [
  "// GENERATED by scripts/private-assets.mjs from the owner's licensed files. Git-ignored:",
  "// never commit or share. Delete this folder's files to fall back to SF Pro / SF Symbols.",
  'import type { PrivateAssets } from "../../src/private/types";',
  "",
];

const fonts = Object.entries(FONT_FILES).filter(([, f]) => existsSync(join(fontsDir, f)));
if (fonts.length === Object.keys(FONT_FILES).length) {
  mkdirSync(join(out, "fonts"));
  for (const [, f] of fonts) copyFileSync(join(fontsDir, f), join(out, "fonts", f));
  lines.push("const fonts = {", ...fonts.map(([name, f]) => `  "${name}": require("./fonts/${f}"),`), "};");
  console.log(`fonts: ${fonts.length} from ${fontsDir}`);
} else {
  lines.push("const fonts = {};");
  console.log(`fonts: skipped (need all of ${Object.values(FONT_FILES).join(", ")} in ${fontsDir})`);
}

if (existsSync(basilFile)) {
  const pack = readBasil(basilFile);
  writeFileSync(join(out, "basil.json"), JSON.stringify(pack));
  mkdirSync(join(out, "bars"));
  const tabs = [];
  for (const role of BAR_ROLES.filter((r) => pack[r])) {
    for (const variant of ["outline", "solid"]) {
      for (const scale of [1, 2, 3]) {
        const name = `${role}-${variant}${scale === 1 ? "" : `@${scale}x`}.png`;
        writeFileSync(join(out, "bars", name), png(pack[role][variant], BAR_POINTS * scale));
      }
    }
    tabs.push(
      `  "${role}": { default: require("./bars/${role}-outline.png"), selected: require("./bars/${role}-solid.png") },`,
    );
  }
  lines.push('const basil = require("./basil.json");', "const barIcons = {", ...tabs, "};");
  console.log(`basil: ${Object.keys(pack).length} icons, bar images for ${BAR_ROLES.filter((r) => pack[r]).join(", ")}`);
} else {
  lines.push("const basil = {};", "const barIcons = {};");
  console.log(`basil: skipped (no ${basilFile}; run \`npm run icons\` in frontend/ first)`);
}

lines.push("", "const assets: PrivateAssets = { fonts, basil, barIcons };", "export default assets;", "");
writeFileSync(join(out, "index.ts"), lines.join("\n"));
console.log(`wrote ${out}`);
